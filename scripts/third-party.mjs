#!/usr/bin/env node
// Regenerates THIRD-PARTY.md: every Rust crate and npm package that ends up
// inside the shipped app, with its version and licence.
//
//   node scripts/third-party.mjs          # rewrite THIRD-PARTY.md
//   node scripts/third-party.mjs --check  # fail if it is out of date (CI)
//
// Rust: what `cargo tree` reports as normal (non-dev, non-build) dependencies
// of the app for each platform we ship. npm: the production dependencies in
// package-lock.json.

import { execFileSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("..", import.meta.url));
const outPath = fileURLToPath(new URL("../THIRD-PARTY.md", import.meta.url));

const TARGETS = [
  "aarch64-apple-darwin",
  "x86_64-unknown-linux-gnu",
  "x86_64-pc-windows-msvc",
];
const OURS = new Set(["splitsound-desktop", "splitsound-core", "splitsound-cli"]);

// npm packages whose package.json states no licence. Each entry was checked
// against the package's source repository and says where.
const NPM_LICENCE_OVERRIDES = {
  // LICENSE_MIT and LICENSE_APACHE-2.0 in github.com/crabnebula-dev/drag-rs
  "@crabnebula/tauri-plugin-drag": "MIT OR Apache-2.0",
};

function rustCrates() {
  const crates = new Map();
  for (const target of TARGETS) {
    const out = execFileSync(
      "cargo",
      ["tree", "--locked", "-p", "splitsound-desktop", "--edges", "normal", "--target", target, "--prefix", "none", "--format", "{p}\t{l}\t{r}"],
      { cwd: root, encoding: "utf8", maxBuffer: 64 * 1024 * 1024 },
    );
    for (const line of out.split("\n")) {
      const [pkg, license, repository] = line.split("\t");
      const match = /^(\S+) v(\S+)/.exec(pkg ?? "");
      if (!match || OURS.has(match[1])) continue;
      crates.set(`${match[1]} ${match[2]}`, {
        name: match[1],
        version: match[2],
        license: license || "not stated",
        url: repository || `https://crates.io/crates/${match[1]}`,
      });
    }
  }
  return [...crates.values()].sort((a, b) => a.name.localeCompare(b.name) || a.version.localeCompare(b.version));
}

function npmPackages() {
  const lock = JSON.parse(readFileSync(new URL("../package-lock.json", import.meta.url), "utf8"));
  const packages = [];
  for (const [path, entry] of Object.entries(lock.packages)) {
    if (path === "" || entry.dev || entry.devOptional || !path.startsWith("node_modules/")) continue;
    const name = path.slice(path.lastIndexOf("node_modules/") + "node_modules/".length);
    packages.push({
      name,
      version: entry.version,
      license: entry.license ?? NPM_LICENCE_OVERRIDES[name] ?? "not stated",
      url: `https://www.npmjs.com/package/${name}`,
    });
  }
  return packages.sort((a, b) => a.name.localeCompare(b.name));
}

function table(rows) {
  return [
    "| Name | Version | Licence |",
    "| --- | --- | --- |",
    ...rows.map((row) => `| [${row.name}](${row.url}) | ${row.version} | ${row.license} |`),
  ].join("\n");
}

const rust = rustCrates();
const npm = npmPackages();

const unstated = [...rust, ...npm].filter((entry) => entry.license === "not stated");
if (unstated.length > 0) {
  console.error(`No licence is recorded for: ${unstated.map((entry) => entry.name).join(", ")}. Check each one and add it to the overrides.`);
  process.exit(1);
}

const text = `# Third-party software

SplitSound is built from the work listed here. This file is generated by
\`node scripts/third-party.mjs\`; do not edit it by hand.

## Bundled with the app

| Component | Licence | Notes |
| --- | --- | --- |
| [ONNX Runtime](https://onnxruntime.ai) | MIT | Microsoft's official shared library, shipped unmodified. Its own third-party notices are in the \`ThirdPartyNotices.txt\` published with it. |
| [LAME](https://lame.sourceforge.io) | LGPL | MP3 export, compiled in through \`mp3lame-sys\`. The app is open source, so it can be rebuilt against another LAME; build the engine with \`--no-default-features\` to leave it out. |
| [Archivo](https://github.com/Omnibus-Type/Archivo) typeface | SIL Open Font License 1.1 | |
| [Just Another Hand](https://fonts.google.com/specimen/Just+Another+Hand) typeface | Apache-2.0 | |

The models are not software dependencies and have their own terms; see
[ml/LICENSES.md](ml/LICENSES.md).

## Rust crates (${rust.length})

${table(rust)}

## npm packages (${npm.length})

${table(npm)}
`;

if (process.argv.includes("--check")) {
  if (readFileSync(outPath, "utf8") !== text) {
    console.error("THIRD-PARTY.md is out of date. Run: node scripts/third-party.mjs");
    process.exit(1);
  }
  console.log("THIRD-PARTY.md is up to date.");
} else {
  writeFileSync(outPath, text);
  console.log(`THIRD-PARTY.md: ${rust.length} Rust crates, ${npm.length} npm packages.`);
}
